CREATE TABLE community_posts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    community_id bigint NOT NULL REFERENCES communities(id) ON DELETE CASCADE,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    client_id uuid NOT NULL,
    request_hash varchar(64) NOT NULL,
    conteudo varchar(4000) NOT NULL,
    possui_imagem boolean NOT NULL DEFAULT false,
    created_at timestamp(6) with time zone NOT NULL,
    edited_at timestamp(6) with time zone,
    deleted_at timestamp(6) with time zone,
    version bigint NOT NULL DEFAULT 0,
    CONSTRAINT uk_community_post_client UNIQUE (user_id, client_id),
    CONSTRAINT ck_community_post_content CHECK (deleted_at IS NOT NULL OR length(trim(conteudo)) > 0 OR possui_imagem)
);
CREATE INDEX idx_community_posts_cursor ON community_posts (community_id, id DESC) WHERE deleted_at IS NULL;
CREATE TABLE community_post_images (
    post_id bigint PRIMARY KEY REFERENCES community_posts(id) ON DELETE CASCADE,
    dados bytea NOT NULL
);
