ALTER TABLE social_contacts ADD COLUMN notification_cycle uuid NOT NULL DEFAULT gen_random_uuid();
CREATE TABLE social_notifications (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 recipient_id bigint NOT NULL,
 actor_id bigint NOT NULL,
 tipo varchar(30) NOT NULL,
 contact_id bigint REFERENCES social_contacts(id) ON DELETE CASCADE,
 contact_cycle uuid,
 comment_id bigint REFERENCES community_comments(id) ON DELETE CASCADE,
 created_at timestamp(6) with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
 read_at timestamp(6) with time zone,
 CHECK(recipient_id > 0 AND actor_id > 0 AND recipient_id <> actor_id),
 CHECK((tipo IN ('SOLICITACAO_CONTATO','CONTATO_ACEITO') AND contact_id IS NOT NULL AND contact_cycle IS NOT NULL AND comment_id IS NULL)
    OR (tipo='COMENTARIO_PUBLICACAO' AND comment_id IS NOT NULL AND contact_id IS NULL AND contact_cycle IS NULL))
);
-- User lifecycles are inherited through the source FKs. Recipients/actors are selected
-- from those sources, avoiding cross-user FK locks inside community transactions.
CREATE UNIQUE INDEX uk_social_notification_contact ON social_notifications(recipient_id,tipo,contact_id,contact_cycle) WHERE contact_id IS NOT NULL;
CREATE UNIQUE INDEX uk_social_notification_comment ON social_notifications(recipient_id,tipo,comment_id) WHERE comment_id IS NOT NULL;
CREATE INDEX idx_social_notifications_page ON social_notifications(recipient_id,id DESC);
CREATE INDEX idx_social_notifications_unread ON social_notifications(recipient_id,id DESC) WHERE read_at IS NULL;
