CREATE TABLE social_contacts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    low_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    high_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    requester_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    recipient_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    status VARCHAR(20) NOT NULL,
    apresentacao VARCHAR(300),
    requested_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_social_contact_pair UNIQUE(low_user_id, high_user_id),
    CONSTRAINT chk_social_contact_order CHECK (low_user_id < high_user_id),
    CONSTRAINT chk_social_contact_participants CHECK (
        (requester_id = low_user_id AND recipient_id = high_user_id)
        OR (requester_id = high_user_id AND recipient_id = low_user_id)),
    CONSTRAINT chk_social_contact_status CHECK (
        status IN ('PENDENTE', 'ACEITA', 'RECUSADA', 'CANCELADA', 'ENCERRADA'))
);
CREATE INDEX ix_social_contact_recipient ON social_contacts(recipient_id, status, updated_at DESC);
CREATE INDEX ix_social_contact_requester ON social_contacts(requester_id, requested_at DESC);

CREATE TABLE social_user_blocks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    blocker_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    blocked_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_social_user_block UNIQUE(blocker_id, blocked_id),
    CONSTRAINT chk_social_user_block_self CHECK (blocker_id <> blocked_id)
);
CREATE INDEX ix_social_user_block_target ON social_user_blocks(blocked_id);
