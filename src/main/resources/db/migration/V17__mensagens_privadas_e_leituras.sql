CREATE TABLE social_private_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contact_id BIGINT NOT NULL REFERENCES social_contacts(id) ON DELETE CASCADE,
    sender_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    conteudo VARCHAR(1000) NOT NULL CHECK (length(trim(conteudo)) > 0),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    client_message_id UUID NOT NULL,
    CONSTRAINT uk_private_message_retry UNIQUE (contact_id, sender_id, client_message_id)
);
CREATE INDEX ix_private_message_cursor ON social_private_messages(contact_id, id);

CREATE TABLE social_private_reads (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contact_id BIGINT NOT NULL REFERENCES social_contacts(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    last_message_id BIGINT NOT NULL CHECK (last_message_id > 0),
    CONSTRAINT uk_private_message_read UNIQUE (contact_id, user_id)
);
