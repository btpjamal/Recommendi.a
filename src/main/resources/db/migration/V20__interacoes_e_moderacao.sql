ALTER TABLE community_posts ADD COLUMN hidden_at timestamp(6) with time zone;
CREATE TABLE community_comments (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 post_id bigint NOT NULL REFERENCES community_posts(id) ON DELETE CASCADE,
 user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 client_id uuid NOT NULL,
 request_hash varchar(64) NOT NULL,
 conteudo varchar(1000) NOT NULL,
 created_at timestamp(6) with time zone NOT NULL,
 edited_at timestamp(6) with time zone,
 deleted_at timestamp(6) with time zone,
 hidden_at timestamp(6) with time zone,
 version bigint NOT NULL DEFAULT 0,
 UNIQUE(user_id,client_id), UNIQUE(id,post_id),
 CHECK(deleted_at IS NOT NULL OR length(trim(conteudo)) > 0)
);
CREATE INDEX idx_community_comments_cursor ON community_comments(post_id,id DESC) WHERE deleted_at IS NULL AND hidden_at IS NULL;
CREATE TABLE community_post_likes (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 post_id bigint NOT NULL REFERENCES community_posts(id) ON DELETE CASCADE,
 user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 created_at timestamp(6) with time zone NOT NULL,
 UNIQUE(post_id,user_id)
);
CREATE TABLE community_reports (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 post_id bigint NOT NULL REFERENCES community_posts(id) ON DELETE CASCADE,
 comment_id bigint,
 reporter_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 target_version bigint NOT NULL,
 reason varchar(30) NOT NULL CHECK(reason IN ('SPAM','OFENSA','CONTEUDO_INADEQUADO','OUTRO')),
 detalhes varchar(500),
 status varchar(20) NOT NULL CHECK(status IN ('ABERTA','ANALISADA')),
 decision varchar(20) CHECK(decision IN ('MANTER','OCULTAR')),
 notas varchar(1000),
 reviewer_id bigint REFERENCES users(id) ON DELETE SET NULL,
 created_at timestamp(6) with time zone NOT NULL,
 reviewed_at timestamp(6) with time zone,
 version bigint NOT NULL DEFAULT 0,
 FOREIGN KEY(comment_id,post_id) REFERENCES community_comments(id,post_id) ON DELETE CASCADE
);
CREATE UNIQUE INDEX uk_community_report_version ON community_reports(reporter_id,post_id,coalesce(comment_id,0),target_version);
CREATE INDEX idx_community_reports_queue ON community_reports(status,id DESC);
